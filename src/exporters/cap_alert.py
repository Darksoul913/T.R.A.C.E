"""
cap_alert.py - SACHET-Compatible Common Alerting Protocol (CAP v1.2) XML Exporter.

Formats high-severity satellite change polygons into OASIS CAP v1.2 XML drafts
compatible with NDMA's SACHET alert dissemination system.
Enforces 'Human-in-the-Loop' governance (marked Draft - Awaiting Official Approval).
"""

import os
import uuid
from datetime import datetime, timezone
import xml.etree.ElementTree as ET
from xml.dom import minidom
from typing import Dict, Any, Optional
import geopandas as gpd


class CAPAlertExporter:
    """Generates OASIS CAP v1.2 XML alert drafts from critical change polygons."""

    @staticmethod
    def generate_cap_xml(
        feature_row: Dict[str, Any],
        sender_id: str = "ChangeIntel-SatelliteEngine@ndma.gov.in",
        authorizing_authority: str = "District Disaster Management Authority (DDMA)"
    ) -> str:
        """
        Creates an OASIS CAP v1.2 compliant XML string for a specific change polygon.
        """
        identifier = f"IND-SACHET-{datetime.now(timezone.utc).strftime('%Y%m%d')}-{feature_row.get('feature_id', 'ALERT')}-{uuid.uuid4().hex[:6].upper()}"
        sent_time = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S+00:00")

        root = ET.Element("alert", xmlns="urn:oasis:names:tc:emergency:cap:1.2")
        ET.SubElement(root, "identifier").text = identifier
        ET.SubElement(root, "sender").text = sender_id
        ET.SubElement(root, "sent").text = sent_time
        ET.SubElement(root, "status").text = "Draft"
        ET.SubElement(root, "msgType").text = "Alert"
        ET.SubElement(root, "scope").text = "Restricted"
        ET.SubElement(root, "restriction").text = "For Official Authorization Only"
        ET.SubElement(root, "note").text = f"Draft alert generated by ChangeIntel AI. Awaiting official verification and sign-off by {authorizing_authority}."

        # Info block (English)
        info = ET.SubElement(root, "info")
        ET.SubElement(info, "language").text = "en-IN"
        ET.SubElement(info, "category").text = "Geo"
        ET.SubElement(info, "event").text = "Rapid Structural Change / Damage Anomaly"
        ET.SubElement(info, "urgency").text = "Immediate" if feature_row.get("severity_tier") == "Critical" else "Expected"
        ET.SubElement(info, "severity").text = "Extreme" if feature_row.get("severity_tier") == "Critical" else "Severe"
        ET.SubElement(info, "certainty").text = "Observed"
        ET.SubElement(info, "headline").text = f"Satellite Change Alert: {feature_row.get('area_sqm', 0)} m² {feature_row.get('change_type', 'Structural Change')} Detected"

        desc = (
            f"Bi-temporal satellite intelligence detected a major change footprint of "
            f"{feature_row.get('area_sqm')} m² at ({feature_row.get('centroid_lat')}, {feature_row.get('centroid_lon')}) "
            f"with confidence {feature_row.get('magnitude', 0.85):.1%}. "
            f"Classification: {feature_row.get('change_type')}. {feature_row.get('summary', '')}"
        )
        ET.SubElement(info, "description").text = desc
        ET.SubElement(info, "instruction").text = (
            "Field officers to verify on site. Satellite encroachment flags are screening results: "
            "check against Development Plan and CRZ maps before any regulatory action."
        )

        # Area block with polygon coordinates
        area_elem = ET.SubElement(info, "area")
        ET.SubElement(area_elem, "areaDesc").text = f"Affected Footprint Near Centroid ({feature_row.get('centroid_lat')}, {feature_row.get('centroid_lon')})"

        # Format polygon coordinates as "lat,lon lat,lon"
        geom = feature_row.get("geometry")
        if geom is not None and hasattr(geom, "exterior"):
            coords_str = " ".join([f"{lat:.6f},{lon:.6f}" for lon, lat in geom.exterior.coords])
            ET.SubElement(area_elem, "polygon").text = coords_str
        elif "centroid_lat" in feature_row and "centroid_lon" in feature_row:
            ET.SubElement(area_elem, "circle").text = f"{feature_row['centroid_lat']},{feature_row['centroid_lon']},0.1"

        # Pretty print XML
        rough_string = ET.tostring(root, "utf-8")
        reparsed = minidom.parseString(rough_string)
        return reparsed.toprettyxml(indent="  ")

    @classmethod
    def export_alert_file(
        cls,
        feature_row: Dict[str, Any],
        output_dir: str = "data/outputs"
    ) -> str:
        """Generates and writes a CAP XML file for a polygon."""
        os.makedirs(output_dir, exist_ok=True)
        feat_id = feature_row.get("feature_id", "CHG_ALERT")
        xml_content = cls.generate_cap_xml(feature_row)
        file_path = os.path.join(output_dir, f"sachet_cap_{feat_id}.xml")

        with open(file_path, "w", encoding="utf-8") as f:
            f.write(xml_content)

        return file_path
