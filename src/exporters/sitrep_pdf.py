"""
sitrep_pdf.py - Automated Executive Situation Report (SitRep) PDF Generator (Feature #12).

Generates a publication-grade, 1-page executive emergency brief from
attributed satellite change detection statistics for District Disaster
Management Authorities (DDMAs) and municipal commissioners.
"""

import os
from datetime import datetime
from typing import Dict, Any, List
from fpdf import FPDF

from src.exporters.cap_alert import EVENT_PROFILES
import geopandas as gpd


class SitRepPDF(FPDF):
    """Custom PDF styled for Emergency Operations Centers."""

    _ASCII = str.maketrans({"\u2013": "-", "\u2014": "-", "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"', "\u2026": "..."})

    def normalize_text(self, text):
        # Core fonts are Latin-1 only; scene labels and OSM place names may not be.
        # ponytail: non-Latin text (e.g. Devanagari) becomes "?"; embed a Unicode TTF if the PDF must show it.
        return super().normalize_text(text.translate(self._ASCII).encode("latin-1", "replace").decode("latin-1"))

    def header(self):
        # Header banner
        self.set_fill_color(24, 43, 73)  # Dark navy blue
        self.rect(0, 0, 210, 22, "F")
        self.set_font("helvetica", "B", 13)
        self.set_text_color(255, 255, 255)
        self.set_xy(10, 6)
        self.cell(0, 6, "DISTRICT EMERGENCY OPERATION CENTER | UDMA RAPID INTELLIGENCE", align="L")
        self.set_font("helvetica", "I", 9)
        self.set_xy(10, 13)
        self.cell(0, 5, "NATIONAL DISASTER MANAGEMENT FRAMEWORK - SATELLITE SITREP", align="L")
        self.ln(15)

    def footer(self):
        self.set_y(-15)
        self.set_font("helvetica", "I", 8)
        self.set_text_color(128, 128, 128)
        self.cell(0, 10, "CONFIDENTIAL & PRIVILEGED - FOR OFFICIAL USE ONLY | Generated by T.R.A.C.E. Engine", align="C")


class SitRepGenerator:
    """Creates a structured 1-page PDF situation report from detected polygons."""

    @classmethod
    def generate_report(
        cls,
        gdf: gpd.GeoDataFrame,
        scene_name: str = "Mumbai Urban Corridor",
        sensor_name: str = "Sentinel-2 Multi-Spectral (10m)",
        analysis_mode: str = "Encroachment / planning audit",
        output_path: str = "data/outputs/sitrep_report.pdf",
        event: str = "encroachment",
        detector_note: str = ""
    ) -> str:
        profile = EVENT_PROFILES.get(event, EVENT_PROFILES["encroachment"])
        analysis_mode = profile["sitrep_mode"]
        os.makedirs(os.path.dirname(output_path), exist_ok=True)

        pdf = SitRepPDF(orientation="P", unit="mm", format="A4")
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        # Metadata Row
        pdf.set_text_color(40, 40, 40)
        pdf.set_font("helvetica", "B", 10)
        pdf.cell(35, 6, "TARGET SECTOR:", border=0)
        pdf.set_font("helvetica", "", 10)
        pdf.cell(70, 6, f"{scene_name}", border=0)

        pdf.set_font("helvetica", "B", 10)
        pdf.cell(30, 6, "REPORT DATE:", border=0)
        pdf.set_font("helvetica", "", 10)
        pdf.cell(50, 6, datetime.now().strftime("%d %b %Y, %H:%M UTC"), border=0, new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("helvetica", "B", 10)
        pdf.cell(35, 6, "SENSOR / GSD:", border=0)
        pdf.set_font("helvetica", "", 10)
        pdf.cell(70, 6, f"{sensor_name}", border=0)

        pdf.set_font("helvetica", "B", 10)
        pdf.cell(30, 6, "OPERATION:", border=0)
        pdf.set_font("helvetica", "", 10)
        pdf.cell(50, 6, f"{analysis_mode}", border=0, new_x="LMARGIN", new_y="NEXT")

        pdf.ln(4)

        # KPI Metric Cards
        total_area = float(gdf["area_sqm"].sum()) if not gdf.empty else 0.0
        critical_count = int((gdf["severity_tier"] == "Critical").sum()) if not gdf.empty else 0
        high_count = int((gdf["severity_tier"] == "High").sum()) if not gdf.empty else 0
        moderate_count = int((gdf["severity_tier"] == "Medium").sum()) if not gdf.empty else 0
        total_count = len(gdf)

        # Draw 4 KPI summary cards
        kpis = [
            ("TOTAL IMPACT AREA", f"{total_area:,.0f} m²", (239, 68, 68)),
            ("CRITICAL SITES (P1)", f"{critical_count} Zones", (220, 38, 38)),
            ("HIGH SEVERITY (P2)", f"{high_count} Zones", (249, 115, 22)),
            ("TOTAL DETECTIONS", f"{total_count} Polygons", (37, 99, 235))
        ]

        card_w = 45
        card_h = 18
        start_x = 10
        y = pdf.get_y()

        for i, (title, val, (r, g, b)) in enumerate(kpis):
            x = start_x + (i * 48)
            pdf.set_fill_color(245, 247, 250)
            pdf.rect(x, y, card_w, card_h, "F")
            # Left accent bar
            pdf.set_fill_color(r, g, b)
            pdf.rect(x, y, 2.5, card_h, "F")

            pdf.set_xy(x + 4, y + 2)
            pdf.set_font("helvetica", "B", 7)
            pdf.set_text_color(100, 100, 100)
            pdf.cell(card_w - 5, 4, title, border=0)

            pdf.set_xy(x + 4, y + 8)
            pdf.set_font("helvetica", "B", 11)
            pdf.set_text_color(r, g, b)
            pdf.cell(card_w - 5, 7, val, border=0)

        pdf.set_y(y + card_h + 6)

        # Executive Summary Paragraph
        pdf.set_font("helvetica", "B", 10)
        pdf.set_text_color(20, 30, 50)
        pdf.cell(0, 6, "EXECUTIVE SITUATION SUMMARY:", new_x="LMARGIN", new_y="NEXT")

        pdf.set_font("helvetica", "", 9)
        pdf.set_text_color(50, 50, 50)
        summary_text = (
            f"Automated change-intelligence detected {total_count} change polygons totaling {total_area:,.0f} m² "
            f"across the surveyed bounds; {critical_count} critical and {high_count} high-priority sites are queued for "
            f"ground verification. Cloud, shadow and no-data areas were not assessed and are mapped separately. "
            f"{detector_note} High-priority footprints are available as draft SACHET-compatible CAP records."
        ).replace("  ", " ")
        pdf.multi_cell(0, 5, summary_text)
        pdf.ln(4)

        # Top Priority Action Zones Table
        pdf.set_font("helvetica", "B", 10)
        pdf.set_text_color(20, 30, 50)
        pdf.cell(0, 6, "PRIORITY TARGET AUDIT TABLE (TOP DETECTIONS):", new_x="LMARGIN", new_y="NEXT")

        # Table Header
        pdf.set_fill_color(230, 235, 245)
        pdf.set_font("helvetica", "B", 8)
        pdf.set_text_color(30, 40, 60)
        pdf.cell(18, 6, "ID", border=1, fill=True)
        pdf.cell(25, 6, "AREA (m²)", border=1, fill=True)
        pdf.cell(22, 6, "SEVERITY", border=1, fill=True)
        pdf.cell(20, 6, "CONFIDENCE", border=1, fill=True)
        pdf.cell(60, 6, "CLASSIFICATION", border=1, fill=True)
        pdf.cell(45, 6, "CENTROID (LAT, LON)", border=1, fill=True, new_x="LMARGIN", new_y="NEXT")

        # Top 6 rows
        pdf.set_font("helvetica", "", 8)
        pdf.set_text_color(50, 50, 50)
        if not gdf.empty:
            sorted_gdf = gdf.sort_values(by="composite_score", ascending=False).head(6)
            for _, row in sorted_gdf.iterrows():
                pdf.cell(18, 5, str(row.get("feature_id", "")), border=1)
                pdf.cell(25, 5, f"{row.get('area_sqm', 0):,.1f}", border=1)
                pdf.cell(22, 5, str(row.get("severity_tier", "")), border=1)
                pdf.cell(20, 5, f"{row.get('magnitude', 0):.1%}", border=1)
                pdf.cell(60, 5, str(row.get("change_type", ""))[:32], border=1)
                pdf.cell(45, 5, f"{row.get('centroid_lat', 0):.4f}, {row.get('centroid_lon', 0):.4f}", border=1, new_x="LMARGIN", new_y="NEXT")

        pdf.ln(5)

        # Immediate Directives & Sign-off Block
        pdf.set_font("helvetica", "B", 9)
        pdf.set_text_color(20, 30, 50)
        pdf.cell(0, 5, "RECOMMENDED IMMEDIATE DIRECTIVES:", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("helvetica", "", 8)
        pdf.set_text_color(60, 60, 60)
        directives = profile["directives"]
        for d in directives:
            pdf.cell(0, 4, d, new_x="LMARGIN", new_y="NEXT")

        pdf.ln(6)

        # Signature Box
        pdf.set_fill_color(250, 250, 252)
        pdf.rect(10, pdf.get_y(), 190, 18, "F")
        pdf.set_xy(15, pdf.get_y() + 2)
        pdf.set_font("helvetica", "I", 7)
        pdf.cell(85, 4, "Prepared By: T.R.A.C.E. Automated Remote Sensing System", border=0)
        pdf.set_xy(115, pdf.get_y())
        pdf.cell(80, 4, "Authorised Signatory / District Magistrate / Municipal Commissioner", border=0, new_x="LMARGIN", new_y="NEXT")
        pdf.set_xy(115, pdf.get_y() + 4)
        pdf.set_font("helvetica", "", 7)
        pdf.cell(80, 4, "Signature: __________________________   Date: _______________", border=0)

        pdf.output(output_path)
        return output_path
